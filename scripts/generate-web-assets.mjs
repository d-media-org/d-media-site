import { createHash } from "node:crypto";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import sharp from "sharp";

const assetRoots = [
  "project-covers",
  "project-pngs",
  "legacy-project-files",
];
const sourceRoot =
  process.env.D_MEDIA_SOURCE_ASSET_ROOT ??
  path.resolve("..", "d . media - site source archive", "assets");
const outputRoot = "public/optimized-assets/project-web";
const manifestPath = "src/lib/generated-web-asset-manifest.ts";
const imagePattern = /\.(png|jpe?g)$/i;

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const pathname = path.join(directory, entry.name);
      return entry.isDirectory() ? walk(pathname) : [pathname];
    }),
  );

  return files.flat();
}

function getOutputName(assetPath) {
  const digest = createHash("sha1").update(assetPath).digest("hex").slice(0, 12);
  const basename = path.basename(assetPath, path.extname(assetPath));
  const slug = basename
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 48) || "asset";

  return `${digest}-${slug}.webp`;
}

await rm(outputRoot, { force: true, recursive: true });
await mkdir(outputRoot, { recursive: true });

const files = (
  await Promise.all(assetRoots.map((root) => walk(path.join(sourceRoot, root))))
).flat().filter((file) => imagePattern.test(file));
const manifest = {};

for (const sourcePath of files) {
  const relativeAssetPath = path.relative(sourceRoot, sourcePath).split(path.sep).join("/");
  const assetPath = `/assets/${relativeAssetPath}`;
  const outputName = getOutputName(assetPath);
  const outputPath = path.join(outputRoot, outputName);
  const outputUrl = `/optimized-assets/project-web/${outputName}`;

  await sharp(sourcePath, { limitInputPixels: false })
    .rotate()
    .resize({ width: 1800, height: 1800, fit: "inside", withoutEnlargement: true })
    .webp({ quality: 80, alphaQuality: 92, effort: 5 })
    .toFile(outputPath);

  manifest[assetPath] = outputUrl;
}

const manifestSource = `// Generated by npm run assets:web. Do not edit manually.
export const generatedWebAssetManifest: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;

await writeFile(manifestPath, manifestSource);
console.log(`Generated ${files.length} web assets.`);
