import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import sharp from "sharp";

const sourceRoot =
  "/Users/m.dragoev/Library/Mobile Documents/com~apple~CloudDocs/d . media/Projects/Old Flyers";
const outputRoot = "public/optimized-assets/project-web/old-flyers";
const dataPath = "astro/src/lib/old-flyer-assets.ts";
const imagePattern = /\.(png|jpe?g)$/i;

function slugify(input) {
  return input
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 56) || "flyer";
}

const files = (await readdir(sourceRoot, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && imagePattern.test(entry.name))
  .map((entry) => path.join(sourceRoot, entry.name));

const filesWithMeta = await Promise.all(
  files.map(async (sourcePath) => {
    const metadata = await sharp(sourcePath, { limitInputPixels: false }).metadata();

    return {
      sourcePath,
      name: path.basename(sourcePath),
      isPortrait: (metadata.height ?? 0) >= (metadata.width ?? 0),
    };
  }),
);

filesWithMeta.sort((left, right) => {
  if (left.isPortrait !== right.isPortrait) {
    return left.isPortrait ? -1 : 1;
  }

  return left.name.localeCompare(right.name, "bg");
});

await rm(outputRoot, { force: true, recursive: true });
await mkdir(outputRoot, { recursive: true });

const items = [];

for (const [index, file] of filesWithMeta.entries()) {
  const outputName = `${String(index + 1).padStart(2, "0")}-${slugify(path.basename(file.name, path.extname(file.name)))}.webp`;
  const outputPath = path.join(outputRoot, outputName);

  await sharp(file.sourcePath, { limitInputPixels: false })
    .rotate()
    .resize({ width: 1800, height: 1800, fit: "inside", withoutEnlargement: true })
    .webp({ quality: 82, alphaQuality: 94, effort: 5 })
    .toFile(outputPath);

  items.push({
    src: `/optimized-assets/project-web/old-flyers/${outputName}`,
    alt: "Архивен флаер от ранни години",
  });
}

const source = `// Generated by scripts/import-old-flyers.mjs. Do not edit manually.
export const oldFlyerItems = ${JSON.stringify(items, null, 2)} as const;
`;

await writeFile(dataPath, source);
console.log(`Imported ${items.length} old flyer assets.`);
