import { execFile } from "node:child_process";
import { mkdir, readdir, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const sourceRoot =
  process.env.D_MEDIA_VIDEO_ROOT ??
  "/Users/m.dragoev/Library/Mobile Documents/com~apple~CloudDocs/d . media/Videos";
const outputRoot = path.resolve("public/optimized-assets/d-media-motion");
const manifestPath = path.resolve("astro/src/lib/d-media-motion-archive.ts");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const pathname = path.join(directory, entry.name);
      return entry.isDirectory() ? walk(pathname) : [pathname];
    }),
  );
  return files.flat();
}

function slugify(value) {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/gu, "-")
    .replace(/^-|-$/gu, "");
}

function titleFromFilename(filename) {
  return path.basename(filename, path.extname(filename)).replace(/\s+/gu, " ").trim();
}

await mkdir(outputRoot, { recursive: true });

const sourceFiles = (await walk(sourceRoot))
  .filter((file) => /\.(mov|mp4|m4v)$/iu.test(file))
  .sort((left, right) =>
    left.localeCompare(right, "en", {
      numeric: true,
      sensitivity: "base",
    }),
  );
const archive = [];

for (const [index, sourcePath] of sourceFiles.entries()) {
  const relativePath = path.relative(sourceRoot, sourcePath);
  const category = path.dirname(relativePath) === "." ? "Other" : path.dirname(relativePath);
  const basename = `${String(index + 1).padStart(3, "0")}-${slugify(relativePath)}`;
  const videoFilename = `${basename}.m4v`;
  const posterFilename = `${basename}.png`;
  const videoPath = path.join(outputRoot, videoFilename);
  const posterPath = path.join(outputRoot, posterFilename);

  try {
    await stat(videoPath);
  } catch {
    await execFileAsync("/usr/bin/avconvert", [
      "--source",
      sourcePath,
      "--preset",
      "PresetAppleM4V720pHD",
      "--output",
      videoPath,
      "--replace",
    ]);
  }

  try {
    await stat(posterPath);
  } catch {
    const temporaryPoster = `${videoPath}.png`;
    await execFileAsync("/usr/bin/qlmanage", ["-t", "-s", "1280", "-o", outputRoot, videoPath]);
    await rename(temporaryPoster, posterPath);
  }

  const videoStats = await stat(videoPath);
  if (videoStats.size >= 25 * 1024 * 1024) {
    await rm(videoPath, { force: true });
    await rm(posterPath, { force: true });
    throw new Error(`Converted file exceeds 25 MiB: ${sourcePath}`);
  }

  archive.push({
    title: titleFromFilename(sourcePath),
    category,
    video: `/optimized-assets/d-media-motion/${videoFilename}`,
    poster: `/optimized-assets/d-media-motion/${posterFilename}`,
    bytes: videoStats.size,
  });

  console.log(`[${index + 1}/${sourceFiles.length}] ${relativePath} -> ${(videoStats.size / 1024 / 1024).toFixed(1)} MiB`);
}

const source = `// Generated by scripts/process-motion-archive.mjs. Do not edit manually.
export const dMediaMotionArchive = ${JSON.stringify(archive, null, 2)} as const;
`;
await writeFile(manifestPath, source);
console.log(`Generated ${archive.length} motion archive entries.`);
